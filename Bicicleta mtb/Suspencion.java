public class Suspencion{
    protected String marca;
    protected String bloqueo;
    protected String tipoSuspencion;
    protected int recorrido;
    protected int diametroBarra;
    protected int sag;
    public Suspencion(String marca, String bloqueo, String tipoSuspencion, int recorrido, int diametroBarra, int sag){
        this.marca = marca;
        this.bloqueo = bloqueo;
        this.tipoSuspencion = tipoSuspencion;
        this.recorrido = recorrido;
        this.diametroBarra = diametroBarra;
        this.sag = sag;
    }
}
